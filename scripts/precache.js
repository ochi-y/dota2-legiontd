const fs = require('fs');
const path = require('path');

// Holds every .vpcf file path found during the scan
const vpcfPaths = [];
// Holds every .vmdl file path found during the scan
const vmdlPaths = [];

// Files to skip (paths relative to the vscripts directory)
const excludeFiles = [
    'hero_demo\\demo_core.lua',
    'hero_demo/demo_core.lua',  // both path separators are supported
    'lua_abilities\\generic\\modifier_dev_status_effect.lua',
    'lua_abilities/generic/modifier_dev_status_effect.lua'
];

// Validate that a resource path is usable
function isValidResourcePath(str, extension) {
    // The path cannot be just the extension itself
    if (str === extension || str === '.' + extension) {
        return false;
    }

    // The path has to be longer than the extension
    if (str.length <= extension.length + 1) {
        return false;
    }

    // The path needs a directory separator and a file name
    // Valid examples: "particles/test.vpcf", "models/hero.vmdl"
    const hasPath = str.includes('/') || str.includes('\\');
    const hasFileName = str.length > extension.length + 2; // the file name needs at least one character

    return hasPath && hasFileName;
}

// Walk the directory recursively
function traverseDirectory(dir, vscriptsPath) {
    const files = fs.readdirSync(dir);

    for (const file of files) {
        const fullPath = path.join(dir, file);
        const stat = fs.statSync(fullPath);

        if (stat.isDirectory()) {
            // Recurse into subdirectories
            traverseDirectory(fullPath, vscriptsPath);
        } else if (path.extname(file) === '.lua') {
            // Skip anything listed in excludeFiles
            const relativePath = path.relative(vscriptsPath, fullPath);
            const shouldExclude = excludeFiles.some(excludePath => {
                return relativePath === excludePath ||
                       relativePath === excludePath.replace(/\\/g, '/') ||
                       relativePath === excludePath.replace(/\//g, '\\');
            });

            if (!shouldExclude) {
                // Process the Lua file
                processLuaFile(fullPath);
            } else {
                console.log(`Skipping excluded file: ${relativePath}`);
            }
        }
    }
}

// Scan a single Lua file for resource paths
function processLuaFile(filePath) {
    try {
        const content = fs.readFileSync(filePath, 'utf-8');

        // Match Lua string literals: "xxx" or 'xxx'
        // The regex captures whatever sits between the quotes
        const stringPattern = /["']([^"']+)["']/g;
        let match;

        while ((match = stringPattern.exec(content)) !== null) {
            const str = match[1];

            // Check for the .vpcf suffix
            if (str.endsWith('.vpcf')) {
                // The string must contain .vpcf exactly once
                const vpcfCount = (str.match(/\.vpcf/g) || []).length;

                if (vpcfCount === 1 && isValidResourcePath(str, '.vpcf')) {
                    // Avoid duplicates
                    if (!vpcfPaths.includes(str)) {
                        console.log(`Found particle effect: ${str}`);
                        console.log(`  at: ${filePath}`);
                        vpcfPaths.push(str);
                    }
                }
            }

            // Check for the .vmdl suffix
            if (str.endsWith('.vmdl')) {
                // The string must contain .vmdl exactly once
                const vmdlCount = (str.match(/\.vmdl/g) || []).length;

                if (vmdlCount === 1 && isValidResourcePath(str, '.vmdl')) {
                    // Avoid duplicates
                    if (!vmdlPaths.includes(str)) {
                        console.log(`Found model file: ${str}`);
                        console.log(`  at: ${filePath}`);
                        vmdlPaths.push(str);
                    }
                }
            }
        }
    } catch (error) {
        console.error(`Failed to read file ${filePath}:`, error.message);
    }
}

// Build the content of the generated Lua file
function generateLuaContent(vpcfPaths, vmdlPaths) {
    const lines = [];

    // Header comments
    lines.push('-- Auto-generated precache list for resources');
    lines.push('-- Generated by scripts/precache.js, do not edit by hand');
    lines.push('');

    // Define the VPCF_PATHS table
    lines.push('local VPCF_PATHS = {');

    // Add every vpcf path
    vpcfPaths.forEach((vpcfPath, index) => {
        const isLast = index === vpcfPaths.length - 1;
        const comma = isLast ? '' : ',';
        lines.push(`    "${vpcfPath}"${comma}`);
    });

    lines.push('}');
    lines.push('');

    // Define the VMDL_PATHS table
    lines.push('local VMDL_PATHS = {');

    // Add every vmdl path
    vmdlPaths.forEach((vmdlPath, index) => {
        const isLast = index === vmdlPaths.length - 1;
        const comma = isLast ? '' : ',';
        lines.push(`    "${vmdlPath}"${comma}`);
    });

    lines.push('}');
    lines.push('');

    // Return both tables
    lines.push('return {');
    lines.push('    vpcf = VPCF_PATHS,');
    lines.push('    vmdl = VMDL_PATHS');
    lines.push('}');
    lines.push('');

    return lines.join('\n');
}

// Entry point
function main() {
    const vscriptsPath = path.resolve(__dirname, '../game/scripts/vscripts');

    console.log('Scanning the vscripts directory...');
    console.log(`Directory: ${vscriptsPath}`);
    console.log('---');

    if (!fs.existsSync(vscriptsPath)) {
        console.error('The vscripts directory does not exist!');
        return;
    }

    traverseDirectory(vscriptsPath, vscriptsPath);

    console.log('---');
    console.log(`Scan complete!`);
    console.log(`  - ${vpcfPaths.length} particle effect files found (.vpcf)`);
    console.log(`  - ${vmdlPaths.length} model files found (.vmdl)`);
    console.log('');

    console.log('All particle effects:');
    vpcfPaths.forEach((p, index) => {
        console.log(`  ${index + 1}. ${p}`);
    });
    console.log('');

    console.log('All model files:');
    vmdlPaths.forEach((p, index) => {
        console.log(`  ${index + 1}. ${p}`);
    });

    // Write the Lua file
    const outputPath = path.resolve(__dirname, '../game/scripts/vscripts/precache_auto.lua');
    const luaContent = generateLuaContent(vpcfPaths, vmdlPaths);

    try {
        fs.writeFileSync(outputPath, luaContent, 'utf-8');
        console.log('');
        console.log('✨ precache_auto.lua generated successfully!');
        console.log(`Output path: ${outputPath}`);
    } catch (error) {
        console.error('Failed to write file:', error.message);
    }

    return { vpcfPaths, vmdlPaths };
}

// Run when invoked directly
if (require.main === module) {
    main();
}

// Exports for other modules
module.exports = {
    main,
    vpcfPaths,
    vmdlPaths
};
